def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "res", "lang")
    os.makedirs(root, exist_ok=True)
    for idx, code in enumerate(["en", "ja", "th"]):
        lines = ["# Lviewer language file (%s). Generated by tools/gen_lang.py - edit there." % code,
                 "# Copy this file to <exe folder>\\lang\\%s.ini to override texts without rebuilding." % code, ""]
        for k in T:
            v = T[k][idx]
            lines.append("%s=%s" % (k, v))
        with open(os.path.join(root, code + ".ini"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    print("wrote", len(T), "keys x 3 languages")

